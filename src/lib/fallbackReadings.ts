function hashCards(cards: DrawnCard[]): number {
  let hash = 0
  for (const dc of cards) {
    for (let i = 0; i < dc.card.id.length; i++) {
      hash = ((hash << 5) - hash + dc.card.id.charCodeAt(i)) | 0
    }
  }
  return Math.abs(hash)
}

/**
 * 获取降级模板解读
 * 根据卡牌 ID 哈希选择最匹配的模板
 * API 不可用时直接调用，用户无感切换
 */
export function getFallbackReading(cards: DrawnCard[]): string {
  const index = hashCards(cards) % TEMPLATES.length
  return TEMPLATES[index]
}
